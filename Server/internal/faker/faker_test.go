const testDeviceCode = "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef"

func TestBuildURLDecryptsToOriginalPassword(t *testing.T) {
	link, err := BuildURL("13800000000", "p@ss word+/=", "张三 同学", testDeviceCode)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(link, LinkBase+"phone=13800000000&pwd=") {
		t.Fatalf("unexpected prefix: %q", link)
	}
	if !strings.Contains(link, "&name=%E5%BC%A0%E4%B8%89+%E5%90%8C%E5%AD%A6&face=&dc="+testDeviceCode) {
		t.Fatalf("name/face/dc not rendered as expected: %q", link)
	}

	parsed, err := url.Parse(link)
	if err != nil {
		t.Fatal(err)
	}
	if parsed.Scheme != "http" || parsed.Host != "cdn.aquamarine5.fun" {
		t.Fatalf("unexpected endpoint: %s", parsed)
	}
	query := parsed.Query()
	if got := query.Get("phone"); got != "13800000000" {
		t.Fatalf("phone = %q", got)
	}
	if got := query.Get("name"); got != "张三 同学" {
		t.Fatalf("name = %q", got)
	}
	if got := query.Get("dc"); got != testDeviceCode {
		t.Fatalf("dc = %q", got)
	}
	if _, ok := query["face"]; !ok {
		t.Fatalf("face parameter must be present and empty: %v", query)
	}
	if got := query.Get("face"); got != "" {
		t.Fatalf("face = %q, want empty", got)
	}

	if got := decryptPassword(t, query.Get("pwd")); got != "p@ss word+/=" {
		t.Fatalf("decrypted password = %q", got)
	}
}

func TestBuildURLRejectsMissingInputs(t *testing.T) {
	cases := []struct{ mobile, password, dc string }{
		{"", "password", testDeviceCode},
		{"13800000000", "", testDeviceCode},
		{"13800000000", "password", ""},
	}
	for _, tc := range cases {
		if _, err := BuildURL(tc.mobile, tc.password, "name", tc.dc); err == nil {
			t.Fatalf("BuildURL(%q, %q, %q) must fail", tc.mobile, tc.password, tc.dc)
		}
	}
}

func TestEncryptPasswordMatchesCSFFormat(t *testing.T) {
	encrypted, err := EncryptPassword("abc")
	if err != nil {
		t.Fatal(err)
	}
	raw, err := base64.StdEncoding.DecodeString(encrypted)
	if err != nil {
		t.Fatalf("pwd is not standard padded base64: %v", err)
	}
	if len(raw)%aes.BlockSize != 0 || len(raw) != 16 {
		t.Fatalf("ciphertext length = %d", len(raw))
	}
	if decryptPassword(t, encrypted) != "abc" {
		t.Fatal("round trip failed")
	}
}

func TestQRPNGIs512SquarePNG(t *testing.T) {
	link := "http://cdn.aquamarine5.fun/?phone=1&pwd=x&name=n&face=&dc=d"
	raw, err := QRPNG(link)
	if err != nil {
		t.Fatal(err)
	}
	img, err := png.Decode(bytes.NewReader(raw))
	if err != nil {
		t.Fatalf("generated bytes are not a PNG: %v", err)
	}
	if b := img.Bounds(); b.Dx() != QRSize || b.Dy() != QRSize {
		t.Fatalf("qr size = %dx%d", b.Dx(), b.Dy())
	}
	if !strings.HasPrefix(DataURL(raw), "data:image/png;base64,") {
		t.Fatal("data URL prefix missing")
	}
}

func decryptPassword(t *testing.T, encoded string) string {
	t.Helper()
	raw, err := base64.StdEncoding.DecodeString(encoded)
	if err != nil {
		t.Fatalf("decode pwd: %v", err)
	}
	block, err := aes.NewCipher([]byte(TransferKey))
	if err != nil {
		t.Fatal(err)
	}
	if len(raw) == 0 || len(raw)%block.BlockSize() != 0 {
		t.Fatalf("invalid ciphertext length %d", len(raw))
	}
	out := make([]byte, len(raw))
	cipher.NewCBCDecrypter(block, []byte(TransferKey)).CryptBlocks(out, raw)
	pad := int(out[len(out)-1])
	if pad <= 0 || pad > block.BlockSize() || pad > len(out) {
		t.Fatalf("invalid padding %d", pad)
	}
	for _, b := range out[len(out)-pad:] {
		if int(b) != pad {
			t.Fatalf("invalid padding bytes")
		}
	}
	return string(out[:len(out)-pad])
}
